#!/usr/bin/env bash
# Generate per-harness agent definitions from harness-neutral role bodies.
#
#   roles/<role>.md                         shared role instructions (edit these)
#   roles/_shared.md                        instructions appended to every role
#   harness/<h>/frontmatter/<role>.yaml     harness-specific frontmatter
#   harness/codex/frontmatter/<role>.toml   Codex metadata
#   harness/<h>/notes/_all.md               harness notes appended to every role
#   harness/<h>/notes/<role>.md             optional role-specific harness notes
#   harness/<h>/agents/<role>.md            GENERATED output (do not edit)
#   harness/codex/agents/devproc_<role>.toml GENERATED Codex output
#   harness/<h>/output-dir                  optional: repo-relative output dir instead
#                                           (Claude Code uses the root agents/ folder,
#                                           the only one its plugin loader discovers)
#
# Usage: scripts/build-agents.sh          regenerate all outputs
#        scripts/build-agents.sh --check  exit 1 if any output is missing or stale
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
check=0
case "${1:-}" in
  --check) check=1 ;;
  "") ;;
  *) echo "usage: $0 [--check]" >&2; exit 2 ;;
esac

render_body() {
  local h=$1 r=$2 dir="$root/harness/$1"
  cat "$root/roles/$r.md"
  printf '\n'
  if [[ -f "$root/roles/_shared.md" ]]; then cat "$root/roles/_shared.md"; printf '\n'; fi
  cat "$dir/notes/_all.md"
  if [[ -f "$dir/notes/$r.md" ]]; then cat "$dir/notes/$r.md"; fi
}

render() {
  local h=$1 r=$2 dir="$root/harness/$1" body
  if [[ "$h" == codex ]]; then
    body="$(render_body "$h" "$r")"
    # Literal multiline strings preserve Markdown backslashes and quotation marks.
    # Reject their delimiter rather than silently producing invalid instructions.
    if [[ "$body" == *"'''"* ]]; then
      echo "harness/codex: instructions for $r contain the TOML delimiter '''" >&2
      return 1
    fi
    printf '# Generated by scripts/build-agents.sh from roles/%s.md and harness/codex/. Edit those sources and regenerate.\n\n' "$r"
    cat "$dir/frontmatter/$r.toml"
    printf "\ndeveloper_instructions = '''\n%s\n'''\n" "$body"
  else
    printf -- '---\n'
    cat "$dir/frontmatter/$r.yaml"
    printf -- '---\n\n'
    printf '<!-- Generated by scripts/build-agents.sh from roles/%s.md and harness/%s/. Edit those sources and regenerate. -->\n\n' "$r" "$h"
    render_body "$h" "$r"
  fi
}

status=0
roles=()
for f in "$root"/roles/*.md; do
  r="$(basename "$f" .md)"
  [[ "$r" == _* ]] || roles+=("$r")
done

for dir in "$root"/harness/*/; do
  h="$(basename "$dir")"
  [[ -d "$dir/frontmatter" ]] || continue
  [[ -f "$dir/notes/_all.md" ]] || { echo "missing harness/$h/notes/_all.md" >&2; status=1; continue; }

  metadata_ext=yaml
  [[ "$h" != codex ]] || metadata_ext=toml
  for fm in "$dir"/frontmatter/*."$metadata_ext"; do
    r="$(basename "$fm" ".$metadata_ext")"
    [[ -f "$root/roles/$r.md" ]] || { echo "harness/$h/frontmatter/$r.$metadata_ext has no roles/$r.md" >&2; status=1; }
  done

  rel="harness/$h/agents"
  if [[ -f "$dir/output-dir" ]]; then rel="$(tr -d '[:space:]' < "$dir/output-dir")"; fi
  (( check )) || mkdir -p "$root/$rel"
  for r in "${roles[@]}"; do
    [[ -f "$dir/frontmatter/$r.$metadata_ext" ]] || { echo "harness/$h is missing frontmatter/$r.$metadata_ext" >&2; status=1; continue; }
    out="$root/$rel/$r.md"
    [[ "$h" != codex ]] || out="$root/$rel/devproc_$r.toml"
    # Render successfully before replacing a file or comparing its contents.
    rendered="$(render "$h" "$r")"
    if (( check )); then
      if [[ ! -f "$out" ]]; then
        echo "missing generated ${out#"$root/"}" >&2; status=1
      elif ! diff -u "$out" <(printf '%s\n' "$rendered") >&2; then
        echo "stale generated ${out#"$root/"} (run scripts/build-agents.sh)" >&2; status=1
      fi
    else
      printf '%s\n' "$rendered" > "$out"
      echo "wrote ${out#"$root/"}"
    fi
  done
done

exit "$status"
